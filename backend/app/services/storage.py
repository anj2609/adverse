"""Binary storage behind a small interface. Local disk works out of the box; an object-store backend
(S3, GCS...) only has to implement the same four methods and be selected with STORAGE_BACKEND."""
import re
from pathlib import Path
from typing import Protocol

from ..config import get_settings
from ..errors import ApiError

_KEY = re.compile(r"^(creatives|fallbacks)/[a-f0-9]{64}(\.thumb)?\.(png|jpeg|webp)$")
CONTENT_TYPES = {"png": "image/png", "jpeg": "image/jpeg", "webp": "image/webp"}


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def exists(self, key: str) -> bool: ...
    def delete(self, key: str) -> None: ...


class LocalStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Keys are generated by the server, but validate anyway: nothing a client sends may reach the filesystem unchecked.
        if not _KEY.match(key):
            raise ApiError(404, "not_found", "File not found")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ApiError(404, "not_found", "File not found")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():  # content-addressed: same bytes, same file
            tmp = path.with_suffix(path.suffix + ".tmp")
            tmp.write_bytes(data)
            tmp.replace(path)

    def read(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise ApiError(404, "not_found", "File not found")
        return path.read_bytes()

    def exists(self, key: str) -> bool:
        try:
            return self._path(key).is_file()
        except ApiError:
            return False

    def delete(self, key: str) -> None:
        path = self._path(key)
        if path.is_file():
            path.unlink()


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        s = get_settings()
        if s.storage_backend != "local":
            raise RuntimeError(f"Unknown STORAGE_BACKEND {s.storage_backend!r}. Only 'local' is built in; add a Storage implementation for others.")
        _storage = LocalStorage(s.storage_path)
    return _storage


def set_storage(storage: Storage | None) -> None:
    global _storage
    _storage = storage
