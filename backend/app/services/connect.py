"""Makes an app ready for ads: the app's own project zip, with AdForge added, so its developer only builds and publishes it.

What changes, and nothing else:
  * lib/adforge/                AdForge itself (the same files a developer would copy by hand)
  * lib/adforge/connection.dart  this AdForge server's address and the app's ID, so a plain `flutter build` just works
  * pubspec.yaml                the packages AdForge uses, added under `dependencies:` (ones the app already has are kept)
  * the file with runApp(...)   the app wrapped once: runApp(AdForgeScope(..., child: <what was there>))
  * ADFORGE.txt                 what changed and how to build

The uploaded zip is read in place, the result is written to a temporary file and streamed back; neither is kept."""
import posixpath
import re
import stat
import tempfile
import zipfile
from pathlib import Path

import yaml

from ..config import get_settings
from ..errors import bad_request
from .scanner import MAX_ENTRIES, MAX_RATIO, MAX_TOTAL, _safe

PACKAGES = {"flutter_riverpod": "^2.6.1", "http": "^1.2.2", "shared_preferences": "^2.3.2", "path_provider": "^2.1.4", "crypto": "^3.0.5"}
LEAVE_OUT = {"build", ".dart_tool", "__MACOSX"}  # build output: regenerated by the developer's build anyway
RUN_APP = re.compile(r"\brunApp\s*\(")
IMPORT = re.compile(r"^[ \t]*import[ \t]+['\"][^'\"\n]+['\"][^;\n]*;[ \t]*$", re.M)


def _closing_paren(src: str, open_at: int) -> int:
    """Index of the ')' matching the '(' at open_at, skipping strings and comments. -1 if unbalanced."""
    depth, i, n = 0, open_at, len(src)
    while i < n:
        if src.startswith("//", i):
            i = src.find("\n", i)
            i = n if i < 0 else i
            continue
        if src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = n if end < 0 else end + 2
            continue
        c = src[i]
        if c in "'\"":
            quote = src[i:i + 3] if src[i:i + 3] in ("'''", '"""') else c
            raw = i > 0 and src[i - 1] == "r"
            j = i + len(quote)
            while j < n and not src.startswith(quote, j):
                j += 2 if src[j] == "\\" and not raw else 1
            i = j + len(quote)
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def wrap_main(src: str, package: str) -> tuple[str, str]:
    """(new source, what happened). Wraps the first runApp(...) once and adds the imports. Already done: unchanged."""
    if "AdForgeScope(" in src or "AdForgeAssets(" in src:
        return src, "already has AdForge"
    m = RUN_APP.search(src, src.find("main(") if "main(" in src else 0)
    if not m:
        return src, ""
    open_at = m.end() - 1
    close_at = _closing_paren(src, open_at)
    if close_at < 0:
        return src, ""
    inner = src[open_at + 1:close_at].strip().rstrip(",").strip()
    settings = "AdForgeSettings(baseUrl: adForgeServer, applicationId: adForgeAppId)"
    if inner.startswith("const "):  # the app's widget is constant: so is the wrapper
        wrapped = f"const AdForgeScope(settings: {settings}, child: {inner[len('const '):].strip()})"
    else:
        wrapped = f"AdForgeScope(settings: const {settings}, child: {inner})"
    src = src[:open_at + 1] + wrapped + src[close_at:]
    imports = f"import 'package:{package}/adforge/adforge.dart';\nimport 'package:{package}/adforge/connection.dart';\n"
    last = list(IMPORT.finditer(src))
    at = min(last[-1].end() + 1, len(src)) if last else 0
    return src[:at] + imports + src[at:], "wrapped runApp(...) in AdForgeScope"


def add_packages(pubspec: str) -> tuple[str, list[str], list[str]]:
    """(new pubspec, added, kept-as-they-were). Text is edited in place so the file keeps its comments and layout."""
    doc = yaml.safe_load(pubspec) or {}
    have = set((doc.get("dependencies") or {}).keys()) if isinstance(doc, dict) else set()
    todo = {k: v for k, v in PACKAGES.items() if k not in have}
    kept = sorted(set(PACKAGES) & have)
    if not todo:
        return pubspec, [], kept
    lines = pubspec.splitlines()
    at = next((i for i, l in enumerate(lines) if re.match(r"^dependencies:\s*(#.*)?$", l)), None)
    if at is None:
        block = ["dependencies:"] + [f"  {k}: {v}" for k, v in todo.items()]
        return pubspec.rstrip("\n") + "\n" + "\n".join(block) + "\n", list(todo), kept
    child = next((l for l in lines[at + 1:] if l.strip() and not l.lstrip().startswith("#")), "  x")
    indent = child[:len(child) - len(child.lstrip())] or "  "
    added = [f"{indent}# added by AdForge"] + [f"{indent}{k}: {v}" for k, v in todo.items()]
    lines[at + 1:at + 1] = added
    return "\n".join(lines) + ("\n" if pubspec.endswith("\n") else ""), list(todo), kept


def connection_dart(server: str, app_id: str) -> str:
    esc = lambda s: s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")  # noqa: E731
    return f"""// Written by AdForge for this app. Where the app asks for its ads, and which app it is in the AdForge portal.
// If your AdForge server moves, change the address here (or build with --dart-define=ADFORGE_URL=...).
// Android emulators reach the computer they run on at 10.0.2.2 instead of localhost.
const adForgeServer = String.fromEnvironment('ADFORGE_URL', defaultValue: '{esc(server)}');
const adForgeAppId = String.fromEnvironment('ADFORGE_APP_ID', defaultValue: '{esc(app_id)}');
"""


def make_ready(fileobj, app_id: str, server: str):
    """Returns (temporary file holding the new zip, project name, report). Raises a 400 with a plain reason if it can't."""
    try:
        zf = zipfile.ZipFile(fileobj)
    except (zipfile.BadZipFile, OSError):
        raise bad_request("bad_zip", "That file is not a readable zip")
    infos = [i for i in zf.infolist() if not i.is_dir()]
    if len(infos) > MAX_ENTRIES or sum(i.file_size for i in infos) > MAX_TOTAL:
        raise bad_request("zip_too_big", "The zip is too big. Zip just the project: lib, assets, pubspec.yaml and the platform folders")
    clean = [i for i in infos if _safe(i.filename) and not stat.S_ISLNK(i.external_attr >> 16)
             and not (i.compress_size and i.file_size / i.compress_size > MAX_RATIO and i.file_size > 1024 ** 2)]

    root, pubspec_info, pubspec = None, None, {}
    for i in sorted((i for i in clean if posixpath.basename(i.filename) == "pubspec.yaml"), key=lambda i: i.filename.count("/")):
        try:
            doc = yaml.safe_load(zf.read(i)) or {}
        except yaml.YAMLError:
            continue
        if isinstance(doc, dict) and ("flutter" in doc or "flutter" in (doc.get("dependencies") or {})):
            root, pubspec_info, pubspec = posixpath.dirname(i.filename), i, doc
            break
    if root is None:
        raise bad_request("not_flutter", "No Flutter pubspec.yaml found in the zip. Zip the project folder (the one with pubspec.yaml)")
    prefix = root + "/" if root else ""
    package = str(pubspec.get("name") or "")
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", package):
        raise bad_request("bad_pubspec", "pubspec.yaml has no valid package name")

    # the file that starts the app: lib/main.dart, else the one file in lib/ that calls runApp
    sources = {i.filename[len(prefix):]: i for i in clean if i.filename.startswith(prefix + "lib/") and i.filename.endswith(".dart")
               and not i.filename.startswith(prefix + "lib/adforge/")}
    candidates = ["lib/main.dart"] if "lib/main.dart" in sources else sorted(r for r, i in sources.items() if RUN_APP.search(zf.read(i).decode("utf-8", "replace")))
    main_rel, main_src, how = None, "", ""
    for rel in candidates:
        text = zf.read(sources[rel]).decode("utf-8")
        new, how = wrap_main(text, package)
        if how:
            main_rel, main_src = rel, new
            break
    if not main_rel:
        raise bad_request("no_run_app", "Couldn't find where the app starts (a runApp(...) call in lib/). Add AdForge by hand: see the setup steps")

    new_pubspec, added, kept = add_packages(zf.read(pubspec_info).decode("utf-8"))
    sdk = Path(get_settings().adforge_sdk_path)
    sdk_files = sorted(p for p in sdk.rglob("*.dart") if p.is_file())
    if not sdk_files:
        raise bad_request("sdk_missing", "This AdForge server can't find its app files (ADFORGE_SDK_PATH)")

    platforms = sorted({i.filename[len(prefix):].split("/")[0] for i in clean if i.filename.startswith(prefix)} & {"android", "ios", "web", "macos", "windows", "linux"})
    report = {"package": package, "main_file": main_rel, "main_change": how, "packages_added": added, "packages_kept": kept,
              "server": server, "app_id": app_id, "platforms": platforms}
    notes = [f"This copy of {package} has AdForge added, so it can show the ads you put on its pictures in the AdForge portal.",
             "", "What changed:", "  lib/adforge/                AdForge (new)",
             f"  lib/adforge/connection.dart  server {server}, app ID {app_id}",
             f"  pubspec.yaml                {'added ' + ', '.join(added) if added else 'nothing to add'}{' (kept your ' + ', '.join(kept) + ')' if kept else ''}",
             f"  {main_rel:<27} {how}", "", "Build and publish it as usual, for example:", "  flutter pub get", "  flutter run    (or flutter build apk / ipa / web)"]
    if not platforms:
        notes += ["", "This project has no android/, ios/ or web/ folder: run \"flutter create .\" once in it before building."]
    if "flutter_riverpod" in kept:
        notes += ["", "Your app already uses flutter_riverpod; AdForge needs version 2.x. If yours is newer, tell your AdForge admin."]

    out = tempfile.SpooledTemporaryFile(max_size=64 * 1024 ** 2)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for i in clean:
            rel = i.filename[len(prefix):] if i.filename.startswith(prefix) else None
            if rel is None or rel.split("/")[0] in LEAVE_OUT or rel.startswith("lib/adforge/") or rel in ("pubspec.yaml", main_rel, "ADFORGE.txt"):
                continue
            with zf.open(i) as src, z.open(i.filename, "w") as dst:
                while chunk := src.read(1024 * 1024):
                    dst.write(chunk)
        z.writestr(prefix + "pubspec.yaml", new_pubspec)
        z.writestr(prefix + main_rel, main_src)
        for p in sdk_files:
            z.writestr(prefix + "lib/adforge/" + p.relative_to(sdk).as_posix(), p.read_bytes())
        z.writestr(prefix + "lib/adforge/connection.dart", connection_dart(server, app_id))
        z.writestr(prefix + "ADFORGE.txt", "\n".join(notes) + "\n")
    out.seek(0)
    return out, package, report
